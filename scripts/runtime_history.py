"""Regenerate src/dstory/_runtime_history.py: the hash of every version of the
project runtime files (story.js, story.css) that dstory has ever shipped.

`dstory bundle` uses it to tell an untouched copy from an older release (safe
to refresh) from one the author edited (kept). Run before every release; a
test fails if the current templates are missing from the history.

    python scripts/runtime_history.py
"""
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "dstory" / "_runtime_history.py"
FILES = ("story.js", "story.css")


def _hash(text: str) -> str:
    import hashlib
    return hashlib.sha256(text.replace("\r\n", "\n").encode("utf-8")).hexdigest()[:16]


def _git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                          encoding="utf-8", check=True).stdout


def main() -> None:
    known: dict[str, set[str]] = {}
    for name in FILES:
        path = f"src/dstory/templates/{name}"
        hashes = set()
        for sha in _git("log", "--all", "--format=%H", "--", path).split():
            try:
                hashes.add(_hash(_git("show", f"{sha}:{path}")))
            except subprocess.CalledProcessError:
                pass                                   # deleted in that commit
        hashes.add(_hash((ROOT / path).read_text(encoding="utf-8")))
        known[name] = hashes
    lines = ['"""Generated by scripts/runtime_history.py. Do not edit.',
             "",
             "Hashes (sha256 of the LF-normalised text, first 16 hex) of every",
             'version of the project runtime files dstory has shipped."""', "",
             "KNOWN = {"]
    for name, hs in known.items():
        lines.append(f"    {name!r}: frozenset({{")
        lines += [f"        {h!r}," for h in sorted(hs)]
        lines.append("    }),")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"{k} {len(v)}" for k, v in known.items()))


if __name__ == "__main__":
    main()
